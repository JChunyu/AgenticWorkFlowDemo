/**
 * Shared generation logic for `sync-docs.mjs` and `verify-docs.mjs`, so the
 * generator and the gate can never disagree about what "in sync" means.
 */
import { readFile } from 'node:fs/promises';
import path from 'node:path';

export const ROOT = path.resolve(import.meta.dirname, '..');
export const CARD_PATH = path.join(ROOT, 'src/constraint-card.md');
export const SKILL_PATH = path.join(ROOT, 'skills/h5-renderer-note-block/SKILL.md');
export const README_PATHS = [path.join(ROOT, 'README.md'), path.join(ROOT, 'README.zh-CN.md')];

export const BLOCK_START = '<!-- constraint-card:start -->';
export const BLOCK_END = '<!-- constraint-card:end -->';

const SKILL_FENCE = '````';

export function cardBody(card) {
  return card.replace(/\s+$/, '');
}

export function skillDocument(card) {
  const body = cardBody(card);
  return `---
name: h5-renderer-note-block
description: 'Generate visual blocks for Obsidian notes using the h5-renderer fence. Use when the user asks for a diagram, comparison card, feature matrix, UI mockup, or any visual block to embed in an Obsidian markdown note.'
---

<!-- Generated by scripts/sync-docs.mjs from src/constraint-card.md. Do not edit by hand. -->

# Obsidian visual block (h5-renderer)

When the target is an Obsidian markdown note and the user wants a *visual* block
(diagram, comparison card, feature matrix, UI mockup), output a single fenced code
block named \`h5-renderer\` instead of \`html\`.

## Hard constraints

The eight rules below are the constraint card, copied verbatim. Rule *n* here is
rule *n* of the card — the mapping is positional and one to one.

${SKILL_FENCE}text
${body}
${SKILL_FENCE}

## Shape

${SKILL_FENCE}h5-renderer
<div class="card">
  <style>
    .card { display: grid; gap: 12px; color: var(--text-normal); }
    .card h3 { margin: 0; }
    .card p { margin: 0; color: var(--text-muted); }
  </style>
  <h3>Title</h3>
  <p>Body</p>
</div>
${SKILL_FENCE}

## When not to use

- The deliverable is a plain markdown table — use markdown.
- The diagram is expressible in Mermaid (flowchart, sequence, gantt) — prefer Mermaid.
- The user wants a standalone \`.html\` file.
`;
}

export function readmeBlock(card) {
  const body = cardBody(card);
  return `${BLOCK_START}
${SKILL_FENCE}text
${body}
${SKILL_FENCE}
${BLOCK_END}`;
}

export function replaceBlock(documentText, nextBlock) {
  const start = documentText.indexOf(BLOCK_START);
  const end = documentText.indexOf(BLOCK_END);
  if (start < 0 || end < 0 || end < start) {
    return null;
  }
  return `${documentText.slice(0, start)}${nextBlock}${documentText.slice(end + BLOCK_END.length)}`;
}

export async function readCard() {
  return readFile(CARD_PATH, 'utf8');
}

export async function readIfExists(file) {
  try {
    return await readFile(file, 'utf8');
  } catch {
    return null;
  }
}
